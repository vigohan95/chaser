/**
 * Reconciliation benchmark: score the matcher against a labelled fixture (tests/fixtures/recon-bench.json).
 * A transaction counts as correct only when the predicted rule AND the allocation set (invoice numbers + amounts)
 * equal the label. Precision / recall are per rule; the same numbers go into docs/RECONCILIATION-BENCHMARK.md,
 * the README and the test that pins them.
 */
import type { Invoice, Transaction } from "../paypal/types";
import { ALL_RULES, matchTransactions, type MatchRule } from "./reconcile";

export type BenchRule = MatchRule | "unmatched";

export interface BenchLabel {
  transaction_id: string;
  scenario: string;
  rule: BenchRule;
  allocations: Array<{ invoice_number: string; amount: number }>;
  note?: string;
}

export interface BenchFile {
  generated_at: string;
  now: string;
  invoices: Invoice[];
  transactions: Transaction[];
  labels: BenchLabel[];
}

export interface RuleScore {
  rule: BenchRule;
  labelled: number;
  predicted: number;
  tp: number;
  precision: number | null;
  recall: number | null;
}

export interface BenchResult {
  transactions: number;
  correct: number;
  accuracy: number;
  /** Correct among transactions the matcher proposes to record automatically (action record_payment / record_refund). */
  auto_record_predicted: number;
  auto_record_correct: number;
  auto_record_precision: number;
  per_rule: RuleScore[];
  misses: Array<{ transaction_id: string; scenario: string; expected: string; got: string }>;
}

const allocKey = (xs: Array<{ invoice_number: string; amount: number }>) => [...xs].map((a) => `${a.invoice_number}:${a.amount.toFixed(2)}`).sort().join("|");

export function scoreBench(file: BenchFile, tolerance = 0.01): BenchResult {
  const { matches, unmatched } = matchTransactions(file.transactions, file.invoices, tolerance);
  const predicted = new Map<string, { rule: BenchRule; allocations: Array<{ invoice_number: string; amount: number }>; action: string }>();
  for (const m of matches) predicted.set(m.transaction_id, { rule: m.rule, allocations: m.allocations.map((a) => ({ invoice_number: a.invoice_number, amount: a.amount })), action: m.action });
  for (const u of unmatched) predicted.set(u.transaction_id, { rule: "unmatched", allocations: [], action: "review" });

  const per = new Map<BenchRule, RuleScore>(ALL_RULES.map((r) => [r, { rule: r, labelled: 0, predicted: 0, tp: 0, precision: null, recall: null }]));
  const misses: BenchResult["misses"] = [];
  let correct = 0;
  let autoPred = 0;
  let autoCorrect = 0;
  for (const label of file.labels) {
    const got = predicted.get(label.transaction_id) ?? { rule: "unmatched" as BenchRule, allocations: [], action: "review" };
    per.get(label.rule)!.labelled += 1;
    per.get(got.rule)!.predicted += 1;
    const ok = got.rule === label.rule && allocKey(got.allocations) === allocKey(label.allocations);
    if (ok) {
      correct += 1;
      per.get(label.rule)!.tp += 1;
    } else misses.push({ transaction_id: label.transaction_id, scenario: label.scenario, expected: `${label.rule} ${allocKey(label.allocations)}`, got: `${got.rule} ${allocKey(got.allocations)}` });
    if (got.action !== "review") {
      autoPred += 1;
      if (ok) autoCorrect += 1;
    }
  }
  for (const r of per.values()) {
    r.precision = r.predicted ? r.tp / r.predicted : null;
    r.recall = r.labelled ? r.tp / r.labelled : null;
  }
  return {
    transactions: file.labels.length,
    correct,
    accuracy: correct / file.labels.length,
    auto_record_predicted: autoPred,
    auto_record_correct: autoCorrect,
    auto_record_precision: autoPred ? autoCorrect / autoPred : 1,
    per_rule: [...per.values()].filter((r) => r.labelled || r.predicted),
    misses,
  };
}

const pct = (x: number | null) => (x === null ? "-" : `${Math.round(x * 1000) / 10}%`);

export function renderBenchMarkdown(file: BenchFile, r: BenchResult): string {
  const rows = r.per_rule.map((s) => `| \`${s.rule}\` | ${s.labelled} | ${s.predicted} | ${s.tp} | ${pct(s.precision)} | ${pct(s.recall)} |`).join("\n");
  const scenarios = [...new Set(file.labels.map((l) => l.scenario))];
  const misses = r.misses.length ? r.misses.map((m) => `| ${m.transaction_id} | ${m.scenario} | ${m.expected} | ${m.got} |`).join("\n") : "| - | none | | |";
  return `# Reconciliation benchmark

Generated by \`npm run bench:recon\` from [\`tests/fixtures/recon-bench.json\`](../tests/fixtures/recon-bench.json): ${file.invoices.length} invoices, **${file.labels.length} labelled transactions** across ${scenarios.length} scenario types (exact, partial, split across several invoices, net-of-fee, memo typos, duplicates, refunds, overpayments, ambiguous pairs, wrong currency, off-invoice payments). The matcher is [\`src/lib/agent/reconcile.ts\`](../src/lib/agent/reconcile.ts); the scorer is [\`src/lib/agent/recon-bench.ts\`](../src/lib/agent/recon-bench.ts) and [\`tests/recon-bench.test.ts\`](../tests/recon-bench.test.ts) pins these numbers.

A transaction is **correct** only when the predicted rule *and* the full allocation set (invoice numbers and amounts) equal the label. Precision = correct / predicted for that rule; recall = correct / labelled for that rule.

**Overall: ${r.correct} / ${r.transactions} correct (${pct(r.accuracy)}).** Of the ${r.auto_record_predicted} transactions the matcher would record without a human (\`record_payment\` / \`record_refund\` actions), ${r.auto_record_correct} are correct (**${pct(r.auto_record_precision)} auto-record precision**); \`review\` matches (ambiguous, amount-only, duplicate) are shown in the match review and never recorded by the agent.

| Rule | Labelled | Predicted | Correct | Precision | Recall |
|---|---:|---:|---:|---:|---:|
${rows}

## Misses

| Transaction | Scenario | Expected | Got |
|---|---|---|---|
${misses}

## How the fixture is built

\`scripts/gen-recon-bench.ts\` writes the fixture deterministically (fixed \`now\` = ${file.now.slice(0, 10)}, transaction ids derived from the scenario name) so the labels are reviewable in the diff. Scenario types and counts:

${scenarios.map((s) => `- \`${s}\`: ${file.labels.filter((l) => l.scenario === s).length}`).join("\n")}

Known limits, on purpose: a legitimate second payment of the same amount within three days with no memo is reported as a duplicate for review (not recorded); a payment that fits two invoices equally is ambiguous (shown, not recorded); a net-of-fee payment is recorded at the net amount, leaving the fee gap on the invoice for the user to write off.
`;
}
